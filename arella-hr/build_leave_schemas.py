# 4. leave_request schemas

write_file("backend/app/schemas/leave_request.py", '"""Pydantic schemas for leave request resources."""\n'
'\n'
'from datetime import date, datetime\n'
'from typing import Optional\n'
'\n'
'from pydantic import BaseModel, Field\n'
'\n'
'\n'
'class LeaveRequestCreate(BaseModel):\n'
'    """Schema for creating a leave request."""\n'
'\n'
'    leave_type_id: int = Field(..., ge=1)\n'
'    start_date: date\n'
'    end_date: date\n'
'    reason: Optional[str] = Field(None, max_length=500)\n'
'\n'
'\n'
'class LeaveRequestUpdate(BaseModel):\n'
'    """Schema for approving or rejecting a leave request."""\n'
'\n'
'    status: str = Field(..., pattern="^(approved|rejected)$")\n'
'    manager_note: Optional[str] = None\n'
'\n'
'\n'
'class LeaveRequestOut(BaseModel):\n'
'    """Leave request response schema."""\n'
'\n'
'    id: int\n'
'    employee_id: int\n'
'    employee_name: str\n'
'    employee_avatar_url: str | None\n'
'    leave_type_id: int\n'
'    leave_type_name: str\n'
'    leave_type_color: str\n'
'    leave_type_is_paid: bool\n'
'    department_id: int | None\n'
'    department_name: str | None\n'
'    start_date: date\n'
'    end_date: date\n'
'    days_requested: float\n'
'    status: str\n'
'    reason: str | None\n'
'    approved_by: int | None\n'
'    approver_name: str | None\n'
'    manager_note: str | None\n'
'    created_at: datetime\n'
'    updated_at: datetime\n'
'\n'
'    model_config = {"from_attributes": True}\n'
'\n'
'\n'
'class LeaveRequestListParams(BaseModel):\n'
'    """Query parameters for listing leave requests."""\n'
'\n'
'    page: int = Field(default=1, ge=1)\n'
'    page_size: int = Field(default=20, ge=1, le=100)\n'
'    status: Optional[str] = None  # pending | approved | rejected\n'
'    leave_type_id: Optional[int] = None\n'
'\n'
'\n'
'class PaginatedLeaveResponse(BaseModel):\n'
'    """Wrapper for paginated leave request responses."""\n'
'\n'
'    items: list[LeaveRequestOut]\n'
'    total: int\n'
'    page: int\n'
'    page_size: int\n'
'    total_pages: int\n'
)

# 5. Update schemas/__init__.py

write_file("backend/app/schemas/__init__.py", '# Pydantic schemas live in dedicated files per model\n')

print("\n--- Schemas complete ---")