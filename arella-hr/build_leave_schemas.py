#!/usr/bin/env python3
"""Build Leave & Attendance Pydantic schemas."""
import os

base = os.path.dirname(os.path.abspath(__file__))

def write_file(rel_path, content):
    full = os.path.join(base, rel_path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w") as f:
        f.write(content)
    print(f"  wrote {rel_path}")

# 1. department schemas

write_file("backend/app/schemas/department.py", '"""Pydantic schemas for department resources."""\n'
'\n'
'from datetime import datetime\n'
'from typing import Optional\n'
'\n'
'from pydantic import BaseModel, Field\n'
'\n'
'\n'
'class DepartmentCreate(BaseModel):\n'
'    """Schema for creating a department."""\n'
'\n'
'    name: str = Field(..., min_length=1, max_length=100)\n'
'    description: Optional[str] = None\n'
'    manager_id: Optional[int] = None\n'
'\n'
'\n'
'class DepartmentUpdate(BaseModel):\n'
'    """Schema for updating a department."""\n'
'\n'
'    name: Optional[str] = Field(None, min_length=1, max_length=100)\n'
'    description: Optional[str] = None\n'
'    manager_id: Optional[int] = None\n'
'\n'
'\n'
'class DepartmentOut(BaseModel):\n'
'    """Department response schema."""\n'
'\n'
'    id: int\n'
'    name: str\n'
'    description: str | None\n'
'    manager_id: int | None\n'
'    created_at: datetime\n'
'    updated_at: datetime\n'
'\n'
'    model_config = {"from_attributes": True}\n'
)

